NAMES = {key: name for key, name, _ in REGIONS}
_COMPILED = [(key, re.compile(pattern)) for key, _, pattern in REGIONS]


def region_key(raw):
    """Ключ субъекта РФ по произвольной записи региона, None — если не распознан."""
    if not raw:
        return None
    s = raw.lower().replace("ё", "е").strip()
    for key, rx in _COMPILED:
        if rx.search(s):
            return key
    return None


def clean_city(raw):
    """Название населённого пункта без «г.», «г», «город» и лишних пробелов."""
    if not raw:
        return ""
    s = re.sub(r"(^|\s)(г\.?|город)(\s|$)", " ", raw.strip(), flags=re.I)
    return re.sub(r"\s+", " ", s).strip(" ,.")
